describe('routePath: golden paths', () => {
  it.each(goldens)('$proves', ({ route, kind, startTrim, endTrim, expected }) => {
    const path = routePath(route, kind, startTrim, endTrim);
    expect(path.d).toBe(expected.d);
    for (const key of ['sx', 'sy', 'sdx', 'sdy', 'ex', 'ey', 'edx', 'edy'] as const) {
      expect(path[key]).toBeCloseTo(expected[key], 9);
    }
  });

  it('refuses a route with a non-finite coordinate instead of writing NaN into the path', () => {
    expect(() => routePath([P(0, 0, 'v'), P(Number.NaN, 10, 'v')], 'linear', 0, 0)).toThrow(
      RangeError
    );
  });
});

describe('isAxisTaggedRoute', () => {
  const tagged = [P(0, 0, 'v'), P(0, 10, 'h')];

  it('accepts a route of two or more points that all carry an axis', () => {
    expect(isAxisTaggedRoute(tagged)).toBe(true);
  });

  it.each([
    ['not an array', { length: 2, 0: tagged[0], 1: tagged[1] }],
    ['a single point', [P(0, 0, 'v')]],
    ['an empty route', []],
    ['one untagged point among tagged ones', [P(0, 0, 'v'), { x: 0, y: 5 }, P(0, 9, 'h')]],
    ['a null point', [P(0, 0, 'v'), null]],
    ['a non-object point', [P(0, 0, 'v'), 'h']],
    ['an axis that is neither v nor h', [P(0, 0, 'v'), { x: 0, y: 5, axis: 'x' }]],
  ])('refuses %s', (_name, points) => {
    expect(isAxisTaggedRoute(points)).toBe(false);
  });
});

describe('ease', () => {
  it.each([
    ['an even S when it runs as far along as across', 100, 100, 0.5],
    ['an even S when it runs further along than across', 10, 100, 0.5],
    ['a quarter at sixteen times as far across as along', 160, 10, 0.25],
    ['four times along over across between the bounds', 100, 10, 0.4],
    ['the floor of a quarter when across is far more than along', 100, 8, 0.32],
    ['a quarter at most, when four times along over across falls under it', 1000, 8, 0.25],
    ['the same share for negative runs', -100, -10, 0.4],
    ['half when there is no across at all', 0, 3, 0.5],
  ])('gives %s', (_name, across, along, expected) => {
    expect(ease(across, along)).toBeCloseTo(expected, 9);
  });
});
