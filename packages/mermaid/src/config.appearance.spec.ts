/**
 * `theme`, `look` and `layout` resolve per diagram type. Checks the order the four sources
 * are consulted in, and that the theme variables follow the theme that actually won.
 */
import { describe, expect, it, beforeEach } from 'vitest';
import {
  defaultConfig,
  getConfig,
  saveConfigFromInitialize,
  setDiagramConfigScope,
  setSiteConfig,
  reset,
} from './config.js';
import { addDiagrams } from './diagram-api/diagram-orchestration.js';
import { getDiagramConfigKey } from './diagram-api/diagramConfigKeys.js';
import { mermaidAPI } from './mermaidAPI.js';
import theme from './themes/index.js';
// @ts-expect-error This file is generated by a custom Vite plugin
import defaultConfigJson from './schemas/config.schema.yaml?only-defaults=true';
// @ts-expect-error Vite's JSON Schema plugin supplies this module during tests.
import configSchema from './schemas/config.schema.yaml';

/** The diagram types that opt in to the colour theme and the neo look. */
const REDESIGNED_DIAGRAMS = {
  flowchart: 'flowchart TD\n  A --> B',
  swimlane: 'swimlane-beta TD\n  A --> B',
  class: 'classDiagram\n  class Duck',
  state: 'stateDiagram-v2\n  [*] --> Still',
  er: 'erDiagram\n  CUSTOMER ||--o{ ORDER : places',
  requirement:
    'requirementDiagram\n  requirement test_req {\n  id: 1\n  text: the test text\n  risk: high\n  verifymethod: test\n  }',
  sequence: 'sequenceDiagram\n  Alice->>John: Hello John',
  usecase: 'usecase-beta\n  actor User1("Customer")',
  venn: 'venn-beta\n  set A\n  set B',
  agentflow: 'agentflow-beta TB\n  a["A"]\n  b["B"]\n  a --> b',
} as const;

/** Types deliberately left on whatever develop already shipped. */
const UNCHANGED_DIAGRAMS = {
  pie: 'pie\n  "Dogs" : 40\n  "Cats" : 60',
  gantt: 'gantt\n  title A\n  section S\n  Task :a1, 2014-01-01, 30d',
  mindmap: 'mindmap\n  root((mindmap))\n    A',
  journey: 'journey\n  title My day\n  section Go to work\n    Make tea: 5: Me',
} as const;

/**
 * The config the renderers are handed for `text`. Scope is bounded to the parse, so it is
 * re-established here over the same directives to read back the resolution it performed.
 */
const configFor = async (text: string) => {
  const { diagramType } = await mermaidAPI.parse(text);
  setDiagramConfigScope(diagramType);
  const config = getConfig();
  setDiagramConfigScope(undefined);
  return config;
};

const resetConfig = () => {
  saveConfigFromInitialize({});
  setSiteConfig({});
  reset();
};

describe('per-diagram appearance defaults', () => {
  beforeEach(() => {
    addDiagrams();
    resetConfig();
  });

  describe('with nothing configured by the user', () => {
    it.each(Object.entries(REDESIGNED_DIAGRAMS))(
      '%s takes redux-color and the neo look',
      async (_type, text) => {
        const config = await configFor(text);
        expect(config.theme).toBe('redux-color');
        expect(config.look).toBe('neo');
      }
    );

    it.each(Object.entries(UNCHANGED_DIAGRAMS))(
      '%s keeps the global default theme and look',
      async (_type, text) => {
        const config = await configFor(text);
        expect(config.theme).toBe('default');
        expect(config.look).toBe('classic');
      }
    );

    it('hands the renderer the theme variables of the theme it resolved', async () => {
      const flowchart = await configFor(REDESIGNED_DIAGRAMS.flowchart);
      expect(flowchart.themeVariables.primaryColor).toBe(
        theme['redux-color'].getThemeVariables().primaryColor
      );

      resetConfig();

      const pie = await configFor(UNCHANGED_DIAGRAMS.pie);
      expect(pie.themeVariables.primaryColor).toBe(theme.default.getThemeVariables().primaryColor);
    });

    it('leaves the layout on dagre except where a diagram type names its own', async () => {
      expect((await configFor(REDESIGNED_DIAGRAMS.class)).layout).toBe('dagre');
      expect((await configFor(UNCHANGED_DIAGRAMS.pie)).layout).toBe('dagre');
      // The one type that names its own -- see `swimlanesDiagram.spec.ts`.
      expect((await configFor(REDESIGNED_DIAGRAMS.swimlane)).layout).toBe('swimlane');
    });
  });

  describe('initialize() outranks the diagram type default', () => {
    it('a global look applies to a diagram type that defaults to another one', async () => {
      mermaidAPI.initialize({ look: 'classic' });
      expect((await configFor(REDESIGNED_DIAGRAMS.flowchart)).look).toBe('classic');
    });

    it('a global theme applies, variables included', async () => {
      mermaidAPI.initialize({ theme: 'dark' });
      const config = await configFor(REDESIGNED_DIAGRAMS.sequence);
      expect(config.theme).toBe('dark');
      expect(config.themeVariables.primaryColor).toBe(theme.dark.getThemeVariables().primaryColor);
    });

    it('a global theme the user set to the schema default still counts as set', async () => {
      mermaidAPI.initialize({ theme: 'default' });
      expect((await configFor(REDESIGNED_DIAGRAMS.er)).theme).toBe('default');
    });

    it('a diagram-scoped value beats the global one the user set alongside it', async () => {
      mermaidAPI.initialize({ look: 'classic', flowchart: { look: 'handDrawn' } });
      expect((await configFor(REDESIGNED_DIAGRAMS.flowchart)).look).toBe('handDrawn');
      expect((await configFor(REDESIGNED_DIAGRAMS.sequence)).look).toBe('classic');
    });

    it('a diagram-scoped value reaches every renderer of that diagram', async () => {
      mermaidAPI.initialize({ class: { theme: 'forest' } });
      // v1 and v2 parse into separate diagram types but share one config section.
      expect((await configFor('classDiagram\n  class Duck')).theme).toBe('forest');
      expect((await configFor('classDiagram-v2\n  class Duck')).theme).toBe('forest');
    });

    it('opts a diagram type into a layout', async () => {
      mermaidAPI.initialize({ er: { layout: 'elk' } });
      expect((await configFor(REDESIGNED_DIAGRAMS.er)).layout).toBe('elk');
      expect((await configFor(REDESIGNED_DIAGRAMS.class)).layout).toBe('dagre');
    });
  });

  describe('the diagram itself outranks everything', () => {
    it('frontmatter beats a diagram type default', async () => {
      const config = await configFor('---\nconfig:\n  look: classic\n---\nflowchart TD\n  A --> B');
      expect(config.look).toBe('classic');
    });

    it('frontmatter beats initialize()', async () => {
      mermaidAPI.initialize({ theme: 'dark' });
      const config = await configFor('---\nconfig:\n  theme: forest\n---\nflowchart TD\n  A --> B');
      expect(config.theme).toBe('forest');
      expect(config.themeVariables.primaryColor).toBe(
        theme.forest.getThemeVariables().primaryColor
      );
    });

    it('a diagram-scoped frontmatter value beats a global one in the same frontmatter', async () => {
      const config = await configFor(
        '---\nconfig:\n  look: classic\n  flowchart:\n    look: handDrawn\n---\nflowchart TD\n  A --> B'
      );
      expect(config.look).toBe('handDrawn');
    });

    it('survives the `init` hook reconfiguring the diagram', async () => {
      // Flowchart's `init` calls `setConfig`, which re-resolves from its own object alone.
      const config = await configFor('---\nconfig:\n  theme: dark\n---\nflowchart TD\n  A --> B');
      expect(config.theme).toBe('dark');
    });

    it('a directive beats a diagram type default', async () => {
      const config = await configFor(`%%{init: {'look': 'classic'}}%%\nflowchart TD\n  A --> B`);
      expect(config.look).toBe('classic');
    });
  });

  describe('scope', () => {
    it('does not leak the previous diagram type into the next one', async () => {
      expect((await configFor(REDESIGNED_DIAGRAMS.flowchart)).theme).toBe('redux-color');
      expect((await configFor(UNCHANGED_DIAGRAMS.pie)).theme).toBe('default');
    });

    it('leaves the global defaults in charge once the parse is over', async () => {
      // Scope lasts exactly as long as the parse or render, so an embedder reading
      // `getConfig()` between them does not get the last diagram's appearance.
      await mermaidAPI.parse(REDESIGNED_DIAGRAMS.flowchart);
      expect(getConfig().theme).toBe('default');
      expect(getConfig().look).toBe('classic');
    });
  });

  describe('rejects a value this build cannot render', () => {
    // `initialize()` normalises an unknown top-level `theme`, so the diagram-scoped keys
    // need the same guard: a name no stylesheet matches renders an unstyled diagram.
    it('falls through an unknown diagram-scoped theme from initialize()', async () => {
      mermaidAPI.initialize({ theme: 'dark', flowchart: { theme: 'totally-bogus' as never } });
      const config = await configFor(REDESIGNED_DIAGRAMS.flowchart);
      expect(config.theme).toBe('dark');
      expect(config.themeVariables.primaryColor).toBe(theme.dark.getThemeVariables().primaryColor);
    });

    it('falls through an unknown diagram-scoped theme from frontmatter', async () => {
      const config = await configFor(
        '---\nconfig:\n  flowchart:\n    theme: totally-bogus\n---\nflowchart TD\n  A --> B'
      );
      expect(config.theme).toBe('redux-color');
      expect(config.themeVariables.primaryColor).toBe(
        theme['redux-color'].getThemeVariables().primaryColor
      );
    });

    it('falls through an unknown diagram-scoped look', async () => {
      mermaidAPI.initialize({ flowchart: { look: 'not-a-look' } as never });
      expect((await configFor(REDESIGNED_DIAGRAMS.flowchart)).look).toBe('neo');
    });

    it.each(['__proto__', 'constructor', 'toString', 'valueOf'])(
      'falls through %s rather than reading it off the theme registry prototype',
      async (inherited) => {
        // These satisfy `in` on an object literal and then have no `getThemeVariables`.
        const config = await configFor(
          `---\nconfig:\n  flowchart:\n    theme: ${inherited}\n---\nflowchart TD\n  A --> B`
        );
        expect(config.theme).toBe('redux-color');
        expect(config.themeVariables.primaryColor).toBe(
          theme['redux-color'].getThemeVariables().primaryColor
        );
      }
    );

    it.each(['__proto__', 'constructor'])(
      'survives %s as a global theme, which never reached the diagram-scoped guard',
      async (inherited) => {
        // The global path predates this PR and threw a bare TypeError out of the render.
        const config = await configFor(
          `---\nconfig:\n  theme: ${inherited}\n---\nflowchart TD\n  A --> B`
        );
        expect(config.themeVariables.primaryColor).toBeDefined();
      }
    );

    it("keeps the 'null' theme sentinel, which disables the pre-defined themes", async () => {
      mermaidAPI.initialize({ flowchart: { theme: 'null' } });
      expect((await configFor(REDESIGNED_DIAGRAMS.flowchart)).theme).toBe('null');
    });

    it('leaves an unknown layout alone -- the registry is extensible', async () => {
      // Resolved at render time by `getRegisteredLayoutAlgorithm`, which falls back to dagre.
      mermaidAPI.initialize({ er: { layout: 'elk' } });
      expect((await configFor(REDESIGNED_DIAGRAMS.er)).layout).toBe('elk');
    });
  });

  describe('the schema is the single source of the defaults', () => {
    it('every appearance default the schema declares reaches defaultConfig', () => {
      // Sections `defaultConfig.ts` rebuilds by hand can silently lose these keys, leaving
      // the diagram type on the global default.
      const sections = Object.entries(
        defaultConfigJson as Record<string, Record<string, unknown> | undefined>
      ).filter(([, value]) => value !== null && typeof value === 'object');

      for (const [section, declared] of sections) {
        for (const key of ['theme', 'look', 'layout'] as const) {
          if (declared?.[key] === undefined) {
            continue;
          }
          expect(
            (defaultConfig as Record<string, Record<string, unknown> | undefined>)[section]?.[key],
            `defaultConfig.${section}.${key} dropped the schema default`
          ).toBe(declared[key]);
        }
      }
    });

    it('validates looks against the enum the schema declares', () => {
      const schema = configSchema as {
        $defs: { BaseDiagramConfig: { properties: { look: { enum: string[] } } } };
      };
      // The runtime allow-list in `config.ts` is written out by hand; this is what stops it
      // drifting from the schema and silently rejecting a newly added look.
      expect(schema.$defs.BaseDiagramConfig.properties.look.enum).toEqual([
        'classic',
        'handDrawn',
        'neo',
      ]);
    });

    it('maps every diagram type to a config key that exists', () => {
      for (const type of Object.keys(REDESIGNED_DIAGRAMS)) {
        expect(defaultConfig).toHaveProperty(getDiagramConfigKey(type));
      }
      expect(getDiagramConfigKey('flowchart-v2')).toBe('flowchart');
      expect(getDiagramConfigKey('flowchart-elk')).toBe('flowchart');
      expect(getDiagramConfigKey('classDiagram')).toBe('class');
      expect(getDiagramConfigKey('stateDiagram')).toBe('state');
    });
  });
});
